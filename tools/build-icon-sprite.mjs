#!/usr/bin/env node
/**
 * Build the UI icon sprite (T-Assets §03, ADR 0006) from a local copy of the
 * `lucide-static` package: one <symbol> per icon, id = the name the design
 * uses, drawn on Lucide's 24 px grid with a 2 px round stroke.
 *
 *   node tools/build-icon-sprite.mjs <path to lucide-static/icons>
 *
 * Fetch the package with `npm pack lucide-static@1.48.0` (or the registry
 * tarball, checked against its integrity hash) and extract it; no dependency
 * is added to the repository. Writes packages/ui/src/icons/sprite.ts and copies
 * Lucide's ISC licence beside it. To add an icon, add it to ICONS and re-run.
 */
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.48.0';

/** Sprite id → Lucide file name. Ids follow T-Assets §03; extras serve the DS 02–05 components. */
const ICONS = {
  // T-Assets §03
  search: 'search',
  calendar: 'calendar',
  users: 'users',
  'map-pin': 'map-pin',
  star: 'star',
  heart: 'heart',
  'message-circle': 'message-circle',
  phone: 'phone',
  download: 'download',
  'wifi-off': 'wifi-off',
  'shield-check': 'shield-check',
  'alert-triangle': 'triangle-alert',
  globe: 'globe',
  sliders: 'sliders-horizontal',
  'chevron-right': 'chevron-right',
  'chevron-left': 'chevron-left',
  menu: 'menu',
  x: 'x',
  check: 'check',
  info: 'info',
  clock: 'clock',
  'credit-card': 'credit-card',
  'file-text': 'file-text',
  home: 'house',
  briefcase: 'briefcase',
  bell: 'bell',
  'layout-dashboard': 'layout-dashboard',
  package: 'package',
  building: 'building-2',
  'bar-chart': 'chart-column',
  settings: 'settings',
  pencil: 'pencil',
  minus: 'minus',
  plus: 'plus',
  sun: 'sun',
  // components (DS 02–05)
  'chevron-down': 'chevron-down',
  'chevron-up': 'chevron-up',
  'arrow-left': 'arrow-left',
  'arrow-right': 'arrow-right',
  'alert-circle': 'circle-alert',
  'check-circle': 'circle-check',
  loader: 'loader-circle',
  'external-link': 'external-link',
  copy: 'copy',
  upload: 'upload',
  mail: 'mail',
  'log-out': 'log-out',
  // customer pages (Home, Destinations, Packages, Compare, Payment)
  zap: 'zap',
  fuel: 'fuel',
  wifi: 'wifi',
  shield: 'shield',
  'cloud-sun': 'cloud-sun',
  route: 'route',
  columns: 'columns-2',
  share: 'share-2',
  lock: 'lock',
  image: 'image',
};

const [, , iconsDir] = process.argv;
if (!iconsDir) {
  console.error('usage: node tools/build-icon-sprite.mjs <lucide-static/icons>');
  process.exit(1);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'packages/ui/src/icons');

const pkg = JSON.parse(readFileSync(join(iconsDir, '..', 'package.json'), 'utf8'));
if (pkg.version !== LUCIDE_VERSION) {
  console.error(`expected lucide-static ${LUCIDE_VERSION}, found ${pkg.version}`);
  process.exit(1);
}

const symbols = Object.entries(ICONS).map(([id, file]) => {
  const svg = readFileSync(join(iconsDir, `${file}.svg`), 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  if (!body || /<script|on\w+=/i.test(body)) {
    throw new Error(`unexpected content in ${file}.svg`);
  }
  return `<symbol id="icon-${id}" viewBox="0 0 24 24">${body}</symbol>`;
});

const names = Object.keys(ICONS)
  .map((id) => `  '${id}',`)
  .join('\n');

const source = `// GENERATED by tools/build-icon-sprite.mjs from lucide-static@${LUCIDE_VERSION} (ISC,
// LICENSE-lucide.txt). Do not edit; add an icon to the tool and re-run it.

export const ICON_NAMES = [
${names}
] as const;

export type IconName = (typeof ICON_NAMES)[number];

export const ICON_SPRITE_SYMBOLS = ${JSON.stringify(symbols.join(''))};
`;

writeFileSync(join(outDir, 'sprite.ts'), source);
copyFileSync(join(iconsDir, '..', 'LICENSE'), join(outDir, 'LICENSE-lucide.txt'));
console.log(`wrote ${Object.keys(ICONS).length} icons to packages/ui/src/icons/sprite.ts`);
